export type AppThemeName = keyof typeof AppThemes;
export type AppThemeMode = 'light' | 'dark';

export const DEFAULT_THEME_NAME: AppThemeName = 'flat';

// Rotulos ficam no i18n, em settings:theme.options.<nome>.
export const APP_THEME_NAMES = Object.keys(AppThemes) as AppThemeName[];

export const isAppThemeName = (value: string | null): value is AppThemeName =>
  value !== null && value in AppThemes;
